pub fn note(s: &str) -> Option<u8> {
    let bytes = s.as_bytes();
    if bytes.is_empty() {
        return None;
    }

    let base = match bytes[0].to_ascii_uppercase() {
        b'C' => 0,
        b'D' => 2,
        b'E' => 4,
        b'F' => 5,
        b'G' => 7,
        b'A' => 9,
        b'B' => 11,
        _ => return None,
    };

    let (accidental, octave_start) = if bytes.len() > 1 {
        match bytes[1] {
            b'#' | b's' | b'S' => (1i8, 2),
            b'b' | b'B' => (-1i8, 2),
            _ => (0i8, 1),
        }
    } else {
        return None;
    };

    let octave_str = &s[octave_start..];
    let octave: i8 = octave_str.parse().ok()?;

    let midi = 12 + (octave as i16 * 12) + base as i16 + accidental as i16;

    if (0..=127).contains(&midi) {
        Some(midi as u8)
    } else {
        None
    }
}
